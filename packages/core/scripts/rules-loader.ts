import { readFileSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";
import { CATEGORIES } from "../src/modules/secrets/rule.ts";
import type { AuthoredRule, SecretRule } from "../src/modules/secrets/rule.ts";
import { VALIDATORS } from "../src/modules/secrets/validators.ts";

export const RULES_DIR = join(dirname(fileURLToPath(import.meta.url)), "..", "rules", "secrets");
export const GENERATED_PATH = join(
  dirname(fileURLToPath(import.meta.url)), "..", "src", "modules", "secrets", "rules.generated.ts",
);

const CONFIDENCES = new Set(["high", "medium", "low"]);
const ALLOWED_KEYS = new Set([
  "id", "label", "category", "confidence", "keywords", "pattern", "flags", "group", "nameGroup",
  "validate", "minEntropy", "generic", "placeholder", "description", "tests",
]);

export interface LoadedRules {
  version: string;
  rules: (AuthoredRule & { file: string })[];
}

/** Reads every rules/secrets/*.yaml file and validates it. Throws with all problems found. */
export function loadAuthoredRules(): LoadedRules {
  const version = readFileSync(join(RULES_DIR, "VERSION"), "utf8").trim();
  const files = readdirSync(RULES_DIR).filter((f) => f.endsWith(".yaml")).sort();
  const rules: LoadedRules["rules"] = [];
  const errors: string[] = [];
  const seen = new Set<string>();

  for (const file of files) {
    const doc = parse(readFileSync(join(RULES_DIR, file), "utf8")) as unknown;
    if (!Array.isArray(doc)) {
      errors.push(`${file}: expected a list of rules`);
      continue;
    }
    for (const raw of doc as Record<string, unknown>[]) {
      const where = `${file}:${String(raw.id ?? "?")}`;
      for (const k of Object.keys(raw)) if (!ALLOWED_KEYS.has(k)) errors.push(`${where}: unknown field "${k}"`);
      for (const k of ["id", "label", "category", "confidence", "pattern", "placeholder", "description"]) {
        if (typeof raw[k] !== "string" || !(raw[k] as string).trim()) errors.push(`${where}: missing "${k}"`);
      }
      const r = raw as unknown as AuthoredRule;
      if (seen.has(r.id)) errors.push(`${where}: duplicate id`);
      seen.add(r.id);
      if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(r.id ?? "")) errors.push(`${where}: id must be kebab-case`);
      if (!(r.category in CATEGORIES)) errors.push(`${where}: unknown category "${r.category}"`);
      if (!CONFIDENCES.has(r.confidence)) errors.push(`${where}: confidence must be high, medium or low`);
      if (!/^[A-Z][A-Z0-9_]*$/.test(r.placeholder ?? "")) errors.push(`${where}: placeholder must be UPPER_SNAKE`);
      if (r.validate && !(r.validate in VALIDATORS)) errors.push(`${where}: unknown validator "${r.validate}"`);
      if (r.flags && !/^[imsu]*$/.test(r.flags)) errors.push(`${where}: flags may only use i, m, s, u`);
      let groups = 0;
      try {
        const re = new RegExp(r.pattern, "gd" + (r.flags ?? ""));
        groups = (new RegExp(`${re.source}|`, re.flags).exec("") ?? []).length - 1;
      } catch (e) {
        errors.push(`${where}: invalid regex (${(e as Error).message})`);
      }
      const group = r.group ?? (groups > 0 ? 1 : 0);
      if (group > groups) errors.push(`${where}: group ${group} does not exist in pattern`);
      if (r.nameGroup !== undefined && r.nameGroup > groups) errors.push(`${where}: nameGroup does not exist`);
      if (!r.tests?.match?.length || !r.tests?.nomatch?.length) {
        errors.push(`${where}: needs at least one tests.match and one tests.nomatch example`);
      }
      rules.push({ ...r, group, file });
    }
  }
  if (errors.length) throw new Error(`Rule validation failed:\n  ${errors.join("\n  ")}`);
  return { version, rules };
}

export function toRuntimeRule(r: AuthoredRule): SecretRule {
  const out: SecretRule = {
    id: r.id,
    label: r.label,
    category: r.category,
    confidence: r.confidence,
    keywords: (r.keywords ?? []).map((k) => String(k).toLowerCase()),
    pattern: r.pattern,
    flags: r.flags ?? "",
    group: r.group ?? 0,
    placeholder: r.placeholder,
    description: r.description,
  };
  if (r.nameGroup !== undefined) out.nameGroup = r.nameGroup;
  if (r.validate) out.validate = r.validate;
  if (r.minEntropy !== undefined) out.minEntropy = r.minEntropy;
  if (r.generic) out.generic = true;
  return out;
}

export function renderGenerated(): string {
  const { version, rules } = loadAuthoredRules();
  const runtime = rules.map(toRuntimeRule);
  return [
    "// GENERATED by scripts/build-rules.ts from rules/secrets/*.yaml. Do not edit by hand.",
    "// Run `npm run build:rules` after changing a rule.",
    'import type { SecretRule } from "./rule.ts";',
    "",
    `export const RULESET_VERSION = ${JSON.stringify(version)};`,
    "",
    `export const RULES: SecretRule[] = ${JSON.stringify(runtime, null, 2)};`,
    "",
  ].join("\n");
}
